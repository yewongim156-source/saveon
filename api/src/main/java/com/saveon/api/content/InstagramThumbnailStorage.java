package com.saveon.api.content;

import io.minio.BucketExistsArgs;
import io.minio.GetObjectArgs;
import io.minio.MakeBucketArgs;
import io.minio.MinioClient;
import io.minio.PutObjectArgs;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.util.Base64;

/** Private storage: upload only when the user explicitly confirms rights. */
@Service
public class InstagramThumbnailStorage {
    private static final int MAX_BYTES = 180_000;
    private final MinioClient minio;
    private final String bucket;

    public InstagramThumbnailStorage(
            @Value("${saveon.thumbnail.minio-url:http://localhost:9010}") String endpoint,
            @Value("${saveon.thumbnail.minio-user:saveonlocal}") String user,
            @Value("${saveon.thumbnail.minio-password:saveonlocal123}") String password,
            @Value("${saveon.thumbnail.bucket:saveon-thumbnails}") String bucket
    ) {
        this.minio = MinioClient.builder()
                .endpoint(endpoint)
                .credentials(user, password)
                .build();
        this.bucket = bucket;
    }

    public String store(long contentId, String jpegBase64) throws Exception {
        byte[] bytes = Base64.getDecoder().decode(jpegBase64);
        if (bytes.length < 100 || bytes.length > MAX_BYTES
                || (bytes[0] & 0xff) != 0xff
                || (bytes[1] & 0xff) != 0xd8
                || (bytes[2] & 0xff) != 0xff) {
            throw new IllegalArgumentException("잘못된 썸네일 JPEG 데이터입니다.");
        }
        if (!minio.bucketExists(BucketExistsArgs.builder().bucket(bucket).build())) {
            try {
                minio.makeBucket(MakeBucketArgs.builder().bucket(bucket).build());
            } catch (Exception concurrentCreation) {
                // Another analysis worker might have created the same bucket.
                if (!minio.bucketExists(BucketExistsArgs.builder().bucket(bucket).build())) {
                    throw concurrentCreation;
                }
            }
        }
        String key = "instagram/content-" + contentId + ".jpg";
        try (ByteArrayInputStream stream = new ByteArrayInputStream(bytes)) {
            minio.putObject(PutObjectArgs.builder()
                    .bucket(bucket)
                    .object(key)
                    .stream(stream, bytes.length, -1)
                    .contentType("image/jpeg")
                    .build());
        }
        return key;
    }

    public byte[] read(String key) throws Exception {
        // Key is generated by this service, not accepted from the HTTP request.
        try (var stream = minio.getObject(GetObjectArgs.builder()
                .bucket(bucket)
                .object(key)
                .build())) {
            return stream.readNBytes(MAX_BYTES + 1);
        }
    }
}
